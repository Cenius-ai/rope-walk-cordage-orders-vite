#!/usr/bin/env bash
# Install every project-level dependency, create the database, seed the demo
# ropemaker and build the frontend. Installs nothing system-wide, starts no
# server, and exits 0.
set -eu
cd "$(dirname "$0")"

PYTHON="${PYTHON:-python3}"
PIP_FLAGS=""

echo "==> Python: ${PYTHON}"
"$PYTHON" --version

# Debian/Ubuntu mark the system interpreter EXTERNALLY-MANAGED (PEP 668). Detect
# it once, then use the same flags for every install below.
if ! "$PYTHON" -m pip install --quiet --upgrade pip setuptools wheel 2>/dev/null; then
  if "$PYTHON" -m pip install --quiet --break-system-packages --upgrade pip setuptools wheel; then
    PIP_FLAGS="--break-system-packages"
    echo "    (PEP 668 environment: using --break-system-packages)"
  else
    echo "!! could not upgrade pip/setuptools/wheel; continuing with installed versions" >&2
  fi
fi

echo "==> Installing backend requirements"
# shellcheck disable=SC2086
"$PYTHON" -m pip install --quiet ${PIP_FLAGS} -r backend/requirements.txt

echo "==> Creating backend/.env with a generated JWT secret (if missing)"
if [ ! -f backend/.env ]; then
  SECRET="$("$PYTHON" -c 'import secrets; print(secrets.token_hex(32))')"
  {
    echo "# Generated by install.sh — development configuration."
    echo "JWT_SECRET=${SECRET}"
  } > backend/.env
  echo "    wrote backend/.env"
else
  echo "    backend/.env already present, left untouched"
fi

echo "==> Creating the SQLite schema and seeding demo data"
(
  cd backend
  "$PYTHON" -m seed
)

echo "==> Installing frontend dependencies"
if [ -f frontend/package-lock.json ]; then
  (cd frontend && npm ci --no-audit --no-fund)
else
  (cd frontend && npm install --no-audit --no-fund)
fi

echo "==> Building the frontend"
(cd frontend && npm run build)

echo "==> Verifying the backend imports"
(cd backend && "$PYTHON" -c "import app.main; print('    app.main imports cleanly')")

cat <<'DONE'

Setup complete.

  Start both services:  sh start.sh
  Backend only:         cd backend && python3 -m uvicorn app.main:app --host 0.0.0.0 --port 8000
  Frontend only:        cd frontend && npm run dev
  Demo login:           cenius@cenius.ai / cenius
DONE
